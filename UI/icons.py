# saved pixmaps so we do not redraw the same icon again
cache = {}


def get_pixmap(name, color="#26344D", size=20):
    key = (name, color, size)
    if key in cache:
        return cache[key]

    paths = icons.get(name, icons["layers"])

    svg = f"""
    <svg xmlns="http://www.w3.org/2000/svg"
         width="{size}" height="{size}"
         viewBox="0 0 24 24">
        <g fill="none"
           stroke="{color}"
           stroke-width="1.8"
           stroke-linecap="round"
           stroke-linejoin="round">
            {paths}
        </g>
    </svg>
    """

    renderer = QSvgRenderer(QByteArray(svg.encode("utf-8")))

    # draw bigger so the icon stays sharp
    scale = 3
    pixmap = QPixmap(size * scale, size * scale)
    pixmap.fill(Qt.GlobalColor.transparent)

    painter = QPainter(pixmap)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    renderer.render(painter)
    painter.end()

    pixmap.setDevicePixelRatio(scale)
    cache[key] = pixmap
    return pixmap


def get_icon(name, color="#26344D", size=20):
    return QIcon(get_pixmap(name, color, size))